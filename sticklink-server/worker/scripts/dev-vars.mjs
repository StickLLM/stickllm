// Write worker/.dev.vars for `wrangler dev --local` using the PUBLIC test
// secrets (same as test/secrets.ts and vectors/signalling-v2.json). These are
// for local/VM testing only; production secrets come from gen-prod-secrets.mjs.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { sha256hex } from "./lib.mjs";

export const DEV = {
  IP_PEPPER: "dev-pepper",
  SIGNING_KEY: "nWGxne_9WmC6hEr0kuwsxERJxWl7MmkZcDusAxyuf2A", // RFC 8032 test 1 seed
  SIGNING_KID: "test-1",
  SIGNING_PUB: "11qYAYKxCrfVS_7TyWQHOg7hcvPapiMlrwIaaPcHURo",
  RELAY_TOKEN: "test-relay-token-tor1-0123456789",
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  // SL_DEV_VARS_OUT: write elsewhere (e2e/start-stack.sh passes it to wrangler with --env-file).
  const out = process.env.SL_DEV_VARS_OUT || new URL("../.dev.vars", import.meta.url);
  const lines = [
    "# Copyright (c) 2026 Nink Inc. All rights reserved.",
    "# LOCAL TEST VALUES ONLY (public test vectors). Generated by scripts/dev-vars.mjs.",
    `IP_PEPPER=${DEV.IP_PEPPER}`,
    `SIGNING_KEY=${DEV.SIGNING_KEY}`,
    `SIGNING_KID=${DEV.SIGNING_KID}`,
    `RELAY_TOKENS={"tor1":"${sha256hex(DEV.RELAY_TOKEN)}"}`,
    // SL_RELAYS lets e2e/start-stack.sh advertise its self-signed derper instead of `derper -dev`.
    ...(process.env.SL_RELAY_REG_PER_DAY ? [`TEST_RELAY_REG_PER_DAY=${process.env.SL_RELAY_REG_PER_DAY}`] : []),
    `RELAYS=${process.env.SL_RELAYS || `[{"rg":"tor1","host":"127.0.0.1","stun":3478,"derp":"http://127.0.0.1:3340/derp"}]`}`,
    `FEATURE_SPAKE2_CODE=${process.env.SL_CODE_FLAG === "1" ? "1" : "0"}`,
  ];
  writeFileSync(out, lines.join("\n") + "\n", { mode: 0o600 });
  console.log(`wrote ${process.env.SL_DEV_VARS_OUT || "worker/.dev.vars"} (test values)`);
}

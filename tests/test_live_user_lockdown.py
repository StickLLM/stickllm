"""v0.5.1: the live 'user' account has no password and no root.

v0.5.0 set user:stickllm and wrote NOPASSWD:ALL for it (console-setup), and
live-config's sudo component wrote /etc/sudoers.d/live on every boot.
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SETUP = ROOT / "overlay" / "usr" / "local" / "bin" / "stickllm-console-setup"
UNIT = ROOT / "overlay" / "etc" / "systemd" / "system" / "stickllm-console-setup.service"
SUDOERS = ROOT / "overlay" / "etc" / "sudoers.d" / "stickllm"
HOOK = ROOT / "live-build" / "hooks" / "normal" / "0100-stickllm-setup.hook.chroot"
VM = ROOT / "scripts" / "vm.ps1"


def _read(p: Path) -> str:
    return p.read_text(encoding="utf-8")


def test_console_setup_never_sets_a_known_password_or_blanket_sudo():
    text = _read(SETUP)
    assert "chpasswd" not in text
    assert "user:stickllm" not in text
    assert "NOPASSWD" not in text
    assert not re.search(r"useradd[^\n]*sudo", text)
    assert not re.search(r"usermod[^\n]*sudo", text)
    assert "user / stickllm" not in text
    assert "v0.3.2" not in text


def test_console_setup_locks_user_and_removes_blanket_sudoers():
    text = _read(SETUP)
    assert "passwd -l user" in text
    assert "gpasswd -d user sudo" in text
    assert "rm -f /etc/sudoers.d/live /etc/sudoers.d/stickllm-user" in text
    # Runs after live-config, which re-adds sudo and writes sudoers.d/live every boot.
    unit = _read(UNIT)
    after = [l for l in unit.splitlines() if l.startswith("After=")]
    assert after and "live-config.service" in after[0]


def test_image_drops_live_config_sudo_component():
    text = _read(HOOK)
    assert "rm -f /lib/live/config/0040-sudo" in text
    assert "passwd -l user" in text


def test_sudoers_has_no_all_rule_for_anyone():
    rules = [l for l in _read(SUDOERS).splitlines() if l.strip() and not l.lstrip().startswith("#")]
    for line in rules:
        assert not re.search(r"NOPASSWD:\s*ALL\b", line), line
        assert "(ALL)" not in line, line
    user = [l for l in rules if l.startswith("user ")]
    assert user == ["user ALL=(root) NOPASSWD: /usr/local/bin/stickllm-wifi-apply, /usr/local/bin/stickllm-wifi-setup"]


def test_no_shipped_text_advertises_the_old_password():
    for rel in ("overlay/usr/local/bin/stickllm-bootstatus", "overlay/usr/local/bin/stickllm-wifi-setup"):
        assert "user / stickllm" not in _read(ROOT / rel), rel


def test_vm_root_runner_is_dev_only():
    text = _read(VM)
    assert "su -c" not in text and "| su " not in text
    assert "sudo -n stickllm-hotfix stickllm-vmtest.service" in text
    # The runner is generated by the harness, never part of the overlay.
    assert not list((ROOT / "overlay").rglob("stickllm-vmtest*"))
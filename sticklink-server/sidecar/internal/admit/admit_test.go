func TestDecisionTable(t *testing.T) {
	c := &clock{t: time.Unix(1_800_000_000, 0)}
	st := NewStore("tor1", "", c.Now)
	now := c.Now().Unix()
	if st.Check(nk(1)) != DenyStale {
		t.Fatal("empty store must deny (stale)")
	}
	full := &Doc{V: 1, Rg: "tor1", Seq: 5, Iat: now, Exp: now + 900, Full: true,
		Add: []Entry{{K: nk(1), E: now + 3600}, {K: nk(2), E: now + 10}}}
	if err := st.Apply(full); err != nil {
		t.Fatal(err)
	}
	table := []struct {
		at   time.Duration
		key  string
		want Decision
	}{
		{0, nk(1), Allow},
		{0, nk(2), Allow},
		{0, nk(3), DenyUnknown},
		{11 * time.Second, nk(2), DenyExpired}, // permit expiry honoured locally
		{11 * time.Second, nk(1), Allow},
		{899 * time.Second, nk(1), Allow},
		{900 * time.Second, nk(1), DenyStale}, // TTL lapsed: fail closed
	}
	base := c.Now()
	for _, r := range table {
		c.t = base.Add(r.at)
		if got := st.Check(r.key); got != r.want {
			t.Errorf("t+%v %s: got %v want %v", r.at, r.key[:12], got, r.want)
		}
	}
}


// ---- fixtures ----

type clock struct {
	mu sync.Mutex
	t  time.Time
}

func (c *clock) Now() time.Time      { c.mu.Lock(); defer c.mu.Unlock(); return c.t }
func (c *clock) Add(d time.Duration) { c.mu.Lock(); c.t = c.t.Add(d); c.mu.Unlock() }

func nk(b byte) string { return "nodekey:" + strings.Repeat(hex.EncodeToString([]byte{b}), 32) }

type signer struct {
	kid string
	sk  ed25519.PrivateKey
}

func newSigner(kid string) signer {
	_, sk, _ := ed25519.GenerateKey(nil)
	return signer{kid, sk}
}

func (s signer) keys() Keys { return Keys{s.kid: s.sk.Public().(ed25519.PublicKey)} }

func (s signer) sign(domain string, d Doc) []byte {
	if d.Kid == "" {
		d.Kid = s.kid
	}
	if d.V == 0 {
		d.V = 1
	}
	body, _ := json.Marshal(d)
	sig := ed25519.Sign(s.sk, SignedInput(domain, body))
	b, _ := json.Marshal(Envelope{Kid: s.kid, Body: b64.EncodeToString(body), Sig: b64.EncodeToString(sig)})
	return b
}

func mustVerify(t *testing.T, ks Keys, raw []byte) *Doc {
	t.Helper()
	d, err := ks.Verify(raw)
	if err != nil {
		t.Fatal(err)
	}
	return d
}

// ---- cross-implementation vectors (generated by Python, signed by the Worker's rules) ----

func TestVectors(t *testing.T) {
	raw, err := os.ReadFile("../../../vectors/signalling-v2.json")
	if err != nil {
		t.Fatal(err)
	}
	var v struct {
		Signing struct{ Pub, Kid string }
		Full    Envelope `json:"allowlist_full"`
		Delta   Envelope `json:"allowlist_delta"`
		Permit  Envelope `json:"permit"`
		Revoked Envelope `json:"revoked"`
	}
	if err := json.Unmarshal(raw, &v); err != nil {
		t.Fatal(err)
	}
	pub, _ := hex.DecodeString(v.Signing.Pub)
	ks := Keys{v.Signing.Kid: pub}
	enc := func(e Envelope) []byte { b, _ := json.Marshal(e); return b }

	full := mustVerify(t, ks, enc(v.Full))
	delta := mustVerify(t, ks, enc(v.Delta))
	if !full.Full || full.Seq != 7 || delta.Full || delta.Since != 7 || delta.Seq != 9 {
		t.Fatalf("unexpected vector docs: %+v %+v", full, delta)
	}
	// Domain separation: permit and revoked-set signatures must NOT verify as allowlists.
	for name, e := range map[string]Envelope{"permit": v.Permit, "revoked": v.Revoked} {
		if _, err := ks.Verify(enc(e)); err == nil || err.Error() != "bad signature" {
			t.Fatalf("%s envelope accepted as allowlist: %v", name, err)
		}
	}
	// Apply chain on a clock at the vector's iat.
	c := &clock{t: time.Unix(full.Iat, 0)}
	st := NewStore("tor1", "", c.Now)
	if err := st.Apply(full); err != nil {
		t.Fatal(err)
	}
	if err := st.Apply(delta); err != nil {
		t.Fatal(err)
	}
	if st.Seq() != 9 {
		t.Fatal("seq")
	}
	for _, k := range delta.Del {
		if st.Check(k) == Allow {
			t.Fatalf("deleted key %s still allowed", k)
		}
	}
	for _, e := range delta.Add {
		if st.Check(e.K) != Allow {
			t.Fatalf("added key %s not allowed", e.K)
		}
	}
}


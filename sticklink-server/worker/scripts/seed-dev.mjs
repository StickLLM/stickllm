// Deterministic local fixtures for StickLLM / AI KVM testing against
// `wrangler dev --local`. Writes fixtures/dev-fixtures.json and
// fixtures/seed.sql; with --apply also loads seed.sql into the LOCAL D1
// (miniflare state under .wrangler/; nothing remote is touched).
//
// Every device auth seed here is derived from a PUBLIC label
// (sha256("sl-fixture/<name>/auth")), so these are test fixtures, not credentials.
// Real devices generate their auth keypair on the device (see provision.mjs).
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { args, b64u, edPub, sqlStr } from "./lib.mjs";
import { DEV } from "./dev-vars.mjs";

const id = (name, n) => createHash("sha256").update("sl-fixture/" + name).digest().subarray(0, n);
const VEC = new URL("../../vectors/", import.meta.url);
const SJ = JSON.parse(readFileSync(new URL("signalling-v2.json", VEC))).slot_join;
const IK = JSON.parse(readFileSync(new URL("ikpsk2-v2.json", VEC)));
const now = Math.floor(Date.now() / 1000);
const year = now + 365 * 86400;

const dev = (name, kind, cls, homeName, homeBytes) => {
  const d = id(name, 16);
  const seed = createHash("sha256").update("sl-fixture/" + name + "/auth").digest();
  return {
    name, kind, dev: b64u(d), gen: 0, home: homeBytes ? b64u(homeBytes) : homeName ? b64u(id(homeName, 16)) : null,
    cls, ent_until: cls === "none" ? 0 : year, auth_seed: b64u(seed), ak: b64u(edPub(seed)),
  };
};
const slot = (name, adm) => ({ name, slot: b64u(id(name + "/slot", 8)), jk: b64u(id(name + "/jk", 32)), adm });

const fx = {
  _copyright: "Copyright (c) 2026 Nink Inc. All rights reserved.",
  _note: "LOCAL TEST FIXTURES derived from public labels. Never use in production.",
  ws: "ws://<host>:8787/v1/ws (subprotocol sticklink.1); from a QEMU user-net guest the host is 10.0.2.2",
  relay: { rg: "tor1", derp: "http://<host>:3340/derp", token: DEV.RELAY_TOKEN, signing_kid: DEV.SIGNING_KID, signing_pub: DEV.SIGNING_PUB },
  devices: {
    stick1: dev("stick1", "stick", "stick", "home1"),
    stick2_noent: dev("stick2", "stick", "none", "home2"),
    kvm1: dev("kvm1", "kvm", "kvm", null),
    kvm2_noent: dev("kvm2", "kvm", "none", null),
    // E2E stick: its home is the vector home (vectors/signalling-v2.json slot_join.home), so the
    // frozen vector chain (pair_psk -> P_slot -> jk/env_k, IKpsk2 prologue) works end to end.
    stick_e2e: dev("stick_e2e", "stick", "stick", null, Buffer.from(SJ.home, "hex")),
  },
  peers: {
    _how: "The stick adds these with slot.add {slot,jk,adm}; a peer then joins with HMAC(jk, 'sl1/join'||n||home||slot).",
    phone_admin: slot("phone", 1),
    laptop: slot("laptop", 0),
    kvm1_slot: slot("kvm1", 0),
  },
};
fx.homes = {
  home1: { home: fx.devices.stick1.home, owner: "stick1" },
  home2: { home: fx.devices.stick2_noent.home, owner: "stick2_noent" },
  home_e2e: { home: fx.devices.stick_e2e.home, owner: "stick_e2e" },
};
fx.e2e = {
  _how: "E2E pairing (stands in for USB/QR pairing). See server/E2E.md. stick_e2e adds slot `slot` with jk at start; kvm1 joins it.",
  home: fx.devices.stick_e2e.home, slot: SJ.slot_b64, jk: SJ.jk_b64, stick: "stick_e2e", kvm: "kvm1",
};

const sql = ["-- Copyright (c) 2026 Nink Inc. All rights reserved.", "-- Generated by scripts/seed-dev.mjs (local test fixtures)."];
for (const d of Object.values(fx.devices))
  sql.push(`INSERT OR REPLACE INTO devices(dev,kind,gen,home,status,cls,ent_until,created,ak) VALUES(${sqlStr(d.dev)},${sqlStr(d.kind)},0,${sqlStr(d.home)},'active',${sqlStr(d.cls)},${d.ent_until},${now},${sqlStr(d.ak)});`);
for (const [, h] of Object.entries(fx.homes))
  sql.push(`INSERT OR REPLACE INTO homes(home,owner,created) VALUES(${sqlStr(h.home)},${sqlStr(fx.devices[h.owner].dev)},${now});`);

const dir = new URL("../fixtures/", import.meta.url);
writeFileSync(new URL("dev-fixtures.json", dir), JSON.stringify(fx, null, 2) + "\n");
writeFileSync(new URL("seed.sql", dir), sql.join("\n") + "\n");
// E2E pairing + identity files (formats in server/E2E.md): TEST keys from vectors/ikpsk2-v2.json.
const CR = "Copyright (c) 2026 Nink Inc. All rights reserved.";
const e2e = new URL("e2e/", dir);
mkdirSync(e2e, { recursive: true });
const wj = (n, o) => writeFileSync(new URL(n, e2e), JSON.stringify({ _copyright: CR, ...o }, null, 2) + "\n", { mode: 0o600 });
wj("pairing.json", {
  format: "sl1-e2e-pairing/1",
  _note: "TEST ONLY. Stands in for the result of USB (kvm-usb) or QR pairing. Both X25519 static keys are pinned here.",
  home: fx.devices.stick_e2e.home, slot: SJ.slot_b64, pair_psk: SJ.pair_psk,
  stick: { static_pub: IK.stick_static_pub }, kvm: { static_pub: IK.kvm_static_pub },
  derived: { P_slot: SJ.P_slot, jk: SJ.jk, env_k: SJ.env_k, prologue: IK.prologue },
});
const ident = (role, d, priv) => ({ format: "sl1-e2e-identity/2", _note: "TEST ONLY private material for one device.", role, dev: d.dev, auth_seed: d.auth_seed, static_priv: priv });
wj("stick.id.json", ident("stick", fx.devices.stick_e2e, IK.stick_static));
wj("kvm.id.json", ident("kvm", fx.devices.kvm1, IK.kvm_static));
console.log("wrote fixtures/dev-fixtures.json, fixtures/seed.sql, fixtures/e2e/{pairing,stick.id,kvm.id}.json");

if (args(process.argv.slice(2)).apply) {
  const cwd = new URL("..", import.meta.url).pathname;
  const env = { ...process.env, WRANGLER_SEND_METRICS: "false" };
  // SL_PERSIST: local state dir (wrangler --persist-to), so parallel stacks don't share D1.
  const pt = process.env.SL_PERSIST ? ["--persist-to", process.env.SL_PERSIST] : [];
  execFileSync("npx", ["wrangler", "d1", "migrations", "apply", "sticklink", "--local", ...pt], { cwd, env, stdio: ["ignore", "ignore", "inherit"] });
  execFileSync("npx", ["wrangler", "d1", "execute", "sticklink", "--local", "--file", "fixtures/seed.sql", ...pt], { cwd, env, stdio: ["ignore", "ignore", "inherit"] });
  console.log("applied migrations + fixtures to the LOCAL D1");
}

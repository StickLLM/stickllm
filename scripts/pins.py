#!/usr/bin/env python3
"""StickLLM verified list: build, check and re-check the pinned hashes.

  python3 scripts/pins.py verify      offline: pins, the add-on table, the
                                      plugin allowlist, the model catalog and
                                      verified.json all agree (CI / before a build)
  python3 scripts/pins.py manifest    regenerate overlay/.../verified.json
  python3 scripts/pins.py upstream    online: ask Docker Hub, GitHub and
                                      Hugging Face whether anything moved.
                                      Exit 1 when something CHANGED.

To approve a new upstream version: update the item's .pin (or allow / catalog
line) with the new digest, run `pins.py manifest`, then `pins.py verify`,
then rebuild. See docs/VERIFIED.md.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import tomllib
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SHARE = ROOT / "overlay/usr/local/share/stickllm"
LIB = ROOT / "overlay/usr/local/lib"
OUT = SHARE / "verified.json"
CATALOG = ROOT / "config/models/catalog.toml"
ALLOW = SHARE / "agent-zero-plugins.allow"
BLOCKED = SHARE / "blocked-apps.list"
DIGEST = re.compile(r"sha256:[0-9a-f]{64}")
SHA = re.compile(r"[0-9a-f]{64}")
SHA40 = re.compile(r"[0-9a-f]{40}")


def parse_pin(path: Path) -> dict:
    doc = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, _, v = line.partition("=")
            doc[k.strip()] = v.strip()
    return doc


def pin_files() -> dict[str, Path]:
    out = {p.stem: p for p in sorted((SHARE / "addons").glob("*.pin"))}
    out["onlyoffice"] = SHARE / "onlyoffice.pin"
    out["agent-zero"] = SHARE / "agent-zero.pin"
    return out


def read_allow() -> dict[str, dict]:
    out = {}
    for raw in ALLOW.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        if len(parts) != 5:
            raise SystemExit(f"bad allow line: {raw!r}")
        name, repo, commit, lic, tree = parts
        out[name] = {"repo": repo, "commit": commit, "license": lic, "tree_sha256": tree}
    return out


def read_models() -> dict[str, str]:
    doc = tomllib.loads(CATALOG.read_text(encoding="utf-8"))
    out = {}
    for m in doc.get("model", []):
        files, shas = m.get("hf_files") or [], m.get("sha256") or []
        if len(files) != len(shas):
            raise SystemExit(f"model {m.get('id')}: hf_files and sha256 differ in length")
        for f, s in zip(files, shas):
            out[f"{m['hf_repo']}/{f}"] = s
    return out


def read_blocked() -> dict[str, str]:
    """blocked-apps.list: "<id> <reason>" per line; # comments."""
    out: dict[str, str] = {}
    for raw in BLOCKED.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        app_id, _, reason = line.partition(" ")
        out[app_id] = reason.strip()
    return out


def build_manifest() -> dict:
    apps = {}
    for app_id, path in pin_files().items():
        pin = parse_pin(path)
        apps[app_id] = {k: pin.get(k, "") for k in ("image", "version", "manifest_digest", "amd64_digest")}
        # Registry tag the upstream check compares; usually the version.
        apps[app_id]["tag"] = pin.get("tag") or pin.get("version", "")
    return {
        "about": "StickLLM verified list. Generated by scripts/pins.py manifest; do not edit by hand.",
        "apps": apps,
        "blocked_apps": read_blocked(),
        "plugins": read_allow(),
        "models": read_models(),
    }


def verify() -> list[str]:
    errors = []
    man = build_manifest()
    for app_id, pin in man["apps"].items():
        for key in ("image", "version"):
            if not pin[key]:
                errors.append(f"app {app_id}: {key} missing")
        for key in ("manifest_digest", "amd64_digest"):
            if not DIGEST.fullmatch(pin[key]):
                errors.append(f"app {app_id}: {key} is not sha256:<64 hex>")
    blocked = man["blocked_apps"]
    for app_id, reason in blocked.items():
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]{1,40}", app_id) or len(reason) < 10:
            errors.append(f"blocked app {app_id}: bad id or reason in blocked-apps.list")
        if app_id in man["apps"]:
            errors.append(f"blocked app {app_id}: also has a .pin (blocked apps are never verified)")
    sys.path.insert(0, str(LIB))
    try:
        import stickllm_verify  # noqa: PLC0415

        if set(blocked) != set(stickllm_verify.BLOCKED_APPS):
            errors.append("blocked-apps.list and stickllm_verify.BLOCKED_APPS differ")
        import stickllm_agent  # noqa: PLC0415

        for app_id in stickllm_agent.CATALOG_APP_IDS:
            if stickllm_verify.app_blocked(app_id, {"blocked_apps": blocked}):
                errors.append(f"blocked app {app_id}: still offered to Agent Zero (CATALOG_APP_IDS)")
        import stickllm_addons  # noqa: PLC0415

        for app_id in stickllm_addons.APPS:
            if app_id in blocked:
                errors.append(f"blocked app {app_id}: still an add-on in stickllm_addons.APPS")

        for app_id, spec in stickllm_addons.APPS.items():
            want = man["apps"].get(app_id)
            if want is None:
                errors.append(f"app {app_id}: in stickllm_addons.APPS but has no .pin")
                continue
            for key in ("image", "version", "manifest_digest", "amd64_digest", "tag"):
                have = str(spec["pin"].get(key, "") or (spec["pin"].get("version", "") if key == "tag" else ""))
                if have != want[key]:
                    errors.append(f"app {app_id}: stickllm_addons.APPS pin {key} differs from {app_id}.pin")
    finally:
        sys.path.pop(0)
    for name, pin in man["plugins"].items():
        if not SHA40.fullmatch(pin["commit"]) or not SHA.fullmatch(pin["tree_sha256"]):
            errors.append(f"plugin {name}: commit or tree_sha256 malformed")
    for key, sha in man["models"].items():
        if not SHA.fullmatch(sha):
            errors.append(f"model {key}: sha256 malformed")
    try:
        shipped = json.loads(OUT.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        errors.append(f"{OUT.relative_to(ROOT)} missing or unreadable; run pins.py manifest")
    else:
        if shipped != man:
            errors.append(f"{OUT.relative_to(ROOT)} is stale; run pins.py manifest")
    return errors


def _get(url: str, headers: dict | None = None, method: str = "GET", timeout: float = 20):
    req = urllib.request.Request(url, headers={"User-Agent": "StickLLM-pins", **(headers or {})}, method=method)
    return urllib.request.urlopen(req, timeout=timeout)


def upstream() -> int:
    sys.path.insert(0, str(LIB))
    import stickllm_verify  # noqa: PLC0415

    man = build_manifest()
    changed = 0
    for app_id, pin in sorted(man["apps"].items()):
        now = stickllm_verify.registry_digest(pin["image"], pin["tag"], timeout=20)
        state = "UNKNOWN (offline?)" if not now else ("VERIFIED" if now == pin["manifest_digest"] else "CHANGED")
        changed += state == "CHANGED"
        print(f"app    {app_id:22} {pin['image']}:{pin['tag']:12} {state}" + (f" now {now}" if state == "CHANGED" else ""))
    for name, pin in sorted(man["plugins"].items()):
        repo = pin["repo"].removeprefix("https://github.com/").removesuffix(".git")
        try:
            with _get(f"https://api.github.com/repos/{repo}/commits/{pin['commit']}",
                      {"Accept": "application/vnd.github+json"}) as r:
                ok = json.load(r).get("sha") == pin["commit"]
            state = "VERIFIED (pinned commit still published)" if ok else "CHANGED"
        except OSError as exc:
            state = "CHANGED (pinned commit gone)" if getattr(exc, "code", 0) in (404, 422) else "UNKNOWN (offline?)"
        changed += state.startswith("CHANGED")
        print(f"plugin {name:22} {repo}@{pin['commit'][:12]} {state}")
    trees: dict[str, dict] = {}
    for key, sha in sorted(man["models"].items()):
        repo, file = key.rsplit("/", 1)
        if repo not in trees:
            try:
                with _get(f"https://huggingface.co/api/models/{repo}/tree/main") as r:
                    trees[repo] = {row.get("path"): ((row.get("lfs") or {}).get("oid") or "") for row in json.load(r)}
            except (OSError, ValueError):
                trees[repo] = {}
        now = trees[repo].get(file, "")
        if not trees[repo]:
            state = "UNKNOWN (offline?)"
        elif not now:
            state = "CHANGED (file gone)"
        else:
            state = "VERIFIED" if now == sha else "CHANGED"
        changed += state.startswith("CHANGED")
        print(f"model  {key} {state}" + (f" now {now}" if state == "CHANGED" else ""))
    return 1 if changed else 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=("verify", "manifest", "upstream"))
    args = ap.parse_args(argv)
    if args.cmd == "manifest":
        OUT.write_text(json.dumps(build_manifest(), indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
        print(f"wrote {OUT.relative_to(ROOT)}")
        return 0
    if args.cmd == "verify":
        errors = verify()
        for e in errors:
            print("FAIL", e)
        print("pins OK" if not errors else f"{len(errors)} problem(s)")
        return 1 if errors else 0
    return upstream()


if __name__ == "__main__":
    raise SystemExit(main())

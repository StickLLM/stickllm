"""Independent (Python) generator for sticklink signalling vectors (sl1).

TEST ONLY. Every value is derived from fixed inputs so the TypeScript Worker,
the Go sidecar and device firmware can cross-check without sharing code.
"""
import base64, hashlib, hmac, json, sys
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.kdf.hkdf import HKDF
from cryptography.hazmat.primitives import hashes

def b64u(b): return base64.urlsafe_b64encode(b).rstrip(b"=").decode()
def H(k, m): return hmac.new(k, m, hashlib.sha256).digest()
def hkdf(ikm, info, n=32): return HKDF(hashes.SHA256(), n, None, info.encode()).derive(ikm)

kvm = json.load(open(sys.argv[1]))["runs"][0]
qr = json.load(open(sys.argv[2]))

out = {"_copyright": "Copyright (c) 2026 Nink Inc. All rights reserved.",
       "spec": "sticklink signalling sl1 (server/API.md); PAIRING-SPEC v0.9", "version": 2,
       "changes_from_v1": "device: HMAC dev_secret/DEV_MASTER hello replaced by a per-device Ed25519 server-auth key (hello sig, auth.rotate pop). Other sections unchanged.",
       "note": "TEST ONLY. Generated by gen_signalling_vectors.py (Python 'cryptography'); verified by the Worker (vitest) and the sidecar (go test).",
       "encoding": "byte fields are hex here; on the wire they are base64url without padding (the *_b64 fields)"}

# 1. device server-auth key + hello (Nink 2026-10-29 Q-S1: per-device random Ed25519 key,
#    generated on the device; the server stores only the public key `ak`)
def ed(seed): return Ed25519PrivateKey.from_private_bytes(seed)
def edpub(k): return k.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
auth_seed = bytes.fromhex("a7" * 32)          # TEST ONLY; real devices draw this from their TRNG
ak = edpub(ed(auth_seed))
dev = bytes.fromhex("a1" * 16)
home = bytes.fromhex(kvm["home_id"])
n = bytes.fromhex("5a" * 32)
hello_in_server = b"sl1/dev-hello/v1" + b"\x00" + n + dev + b"\x01" + home
hello_in_client = b"sl1/dev-hello/v1" + b"\x00" + n + dev + b"\x02" + b"\x00" * 16
hs, hc = ed(auth_seed).sign(hello_in_server), ed(auth_seed).sign(hello_in_client)
new_seed = bytes.fromhex("b8" * 32)
new_ak = edpub(ed(new_seed))
rot_in = b"sl1/dev-rotate/v1" + b"\x00" + n + dev + new_ak + ak
pop = ed(new_seed).sign(rot_in)
out["device"] = {"auth_seed": auth_seed.hex(), "auth_seed_b64": b64u(auth_seed), "ak": ak.hex(), "ak_b64": b64u(ak),
                 "dev": dev.hex(), "dev_b64": b64u(dev), "nonce": n.hex(), "nonce_b64": b64u(n), "home": home.hex(), "home_b64": b64u(home),
                 "hello_rule": "sig = Ed25519(auth_key, 'sl1/dev-hello/v1' || 0x00 || n(32) || dev(16) || role(1: 0x01 server, 0x02 client) || home(16; zeros for client))",
                 "hello_input_server": hello_in_server.hex(), "hello_sig_server": hs.hex(), "hello_sig_server_b64": b64u(hs),
                 "hello_input_client": hello_in_client.hex(), "hello_sig_client": hc.hex(), "hello_sig_client_b64": b64u(hc),
                 "wire_hello_server": json.dumps({"t": "hello", "id": 1, "dev": b64u(dev), "role": "server", "home": b64u(home), "sig": b64u(hs)}, separators=(",", ":")),
                 "wire_hello_client": json.dumps({"t": "hello", "id": 1, "dev": b64u(dev), "role": "client", "sig": b64u(hc)}, separators=(",", ":")),
                 "rotate_rule": "pop = Ed25519(NEW auth_key, 'sl1/dev-rotate/v1' || 0x00 || n(32) || dev(16) || new_ak(32) || old_ak(32)); sent on an authenticated socket",
                 "rotate_new_seed": new_seed.hex(), "rotate_new_ak": new_ak.hex(), "rotate_new_ak_b64": b64u(new_ak),
                 "rotate_input": rot_in.hex(), "rotate_pop": pop.hex(), "rotate_pop_b64": b64u(pop)}

# 2. slot join (chain from PAIRING-SPEC: pair_psk -> P_slot -> jk / env_k)
pair_psk = bytes.fromhex(kvm["pair_psk"])
P_slot = hkdf(pair_psk, "sl1/slot-secret")
jk = hkdf(P_slot, "sl1/join")
env_k = hkdf(P_slot, "sl1/env")
assert P_slot.hex() == kvm["P_slot"] and jk.hex() == kvm["slot_jk"] and env_k.hex() == kvm["slot_env_k"], "kvm-usb-v1 chain mismatch"
slot = bytes.fromhex(kvm["slot_id"])
join_mac = H(jk, b"sl1/join" + n + home + slot)
out["slot_join"] = {"pair_psk": pair_psk.hex(), "P_slot": P_slot.hex(), "jk": jk.hex(), "jk_b64": b64u(jk), "env_k": env_k.hex(),
                    "home": home.hex(), "slot": slot.hex(), "slot_b64": b64u(slot), "nonce": n.hex(),
                    "join_mac": join_mac.hex(), "join_mac_b64": b64u(join_mac),
                    "wire_join": json.dumps({"t": "join", "id": 1, "home": b64u(home), "slot": b64u(slot), "mac": b64u(join_mac)}, separators=(",", ":"))}

# 3. QR mailbox join (reproduces qr-v1.json)
jk_qr = hkdf(bytes.fromhex(qr["invite_secret"]), "sl1/qr-join")
assert jk_qr.hex() == qr["jk_qr"]
qmac = H(jk_qr, b"sl1/qr-join-mac" + bytes.fromhex(qr["server_nonce"]) + bytes.fromhex(qr["mailbox_id"]))
assert qmac.hex() == qr["join_mac"]
out["qr_join"] = {"jk_qr": jk_qr.hex(), "jk_qr_b64": b64u(jk_qr), "mbx": qr["mailbox_id"], "mbx_b64": b64u(bytes.fromhex(qr["mailbox_id"])),
                  "nonce": qr["server_nonce"], "nonce_b64": b64u(bytes.fromhex(qr["server_nonce"])), "join_mac": qmac.hex(), "join_mac_b64": b64u(qmac)}

# 4. Ed25519 signatures (permit, allowlist, revoked set)
seed = bytes.fromhex("9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60")  # RFC 8032 test 1
sk = Ed25519PrivateKey.from_private_bytes(seed)
pub = sk.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
def env(domain, obj):
    body = json.dumps(obj, separators=(",", ":")).encode()
    sig = sk.sign(domain.encode() + b"\x00" + body)
    return {"kid": "test-1", "body": b64u(body), "sig": b64u(sig), "body_json": body.decode()}
nk = "nodekey:" + "ab" * 32
out["signing"] = {"seed": seed.hex(), "seed_b64": b64u(seed), "pub": pub.hex(), "pub_b64": b64u(pub), "kid": "test-1",
                  "rule": "sig = Ed25519(domain || 0x00 || body); body is the exact signed JSON bytes, sent base64url"}
p = env("sl1/permit/v1", {"v": 1, "kid": "test-1", "nk": nk, "rg": "tor1", "exp": 1800000000, "cls": "stick"})
p["tok"] = p["body"] + "." + p["sig"]
out["permit"] = p
out["allowlist_full"] = env("sl1/allowlist/v1", {"v": 1, "kid": "test-1", "rg": "tor1", "seq": 7, "since": 0, "iat": 1799999000, "exp": 1799999900,
                                                 "full": True, "add": [{"k": nk, "e": 1800000000}], "del": []})
out["allowlist_delta"] = env("sl1/allowlist/v1", {"v": 1, "kid": "test-1", "rg": "tor1", "seq": 9, "since": 7, "iat": 1799999060, "exp": 1799999960,
                                                  "full": False, "add": [], "del": [nk]})
out["revoked"] = env("sl1/revoked/v1", {"v": 1, "home": b64u(home), "n": b64u(n), "after": 0, "next": 1, "more": False, "rc": 1,
                                        "iat": 1799999000, "s": [b64u(slot)]})
json.dump(out, open(sys.argv[3], "w"), indent=1)
print("wrote", sys.argv[3])

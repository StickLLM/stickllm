func TestVerifyRejects(t *testing.T) {
	s := newSigner("k1")
	ks := s.keys()
	good := s.sign(DomAllowlist, Doc{Rg: "tor1", Seq: 1, Full: true})
	mustVerify(t, ks, good)

	other := newSigner("k1") // same kid, different key
	cases := map[string][]byte{
		"wrong key":    other.sign(DomAllowlist, Doc{Rg: "tor1", Seq: 1, Full: true}),
		"wrong domain": s.sign("sl1/permit/v1", Doc{Rg: "tor1", Seq: 1, Full: true}),
		"unknown kid":  newSigner("k9").sign(DomAllowlist, Doc{Rg: "tor1", Seq: 1, Full: true}),
		"bad version":  s.sign(DomAllowlist, Doc{V: 2, Rg: "tor1", Seq: 1, Full: true}),
		"body kid":     s.sign(DomAllowlist, Doc{Kid: "k2", Rg: "tor1", Seq: 1, Full: true}),
		"bad add key":  s.sign(DomAllowlist, Doc{Rg: "tor1", Seq: 1, Full: true, Add: []Entry{{K: "nodekey:XYZ", E: 1}}}),
		"bad del key":  s.sign(DomAllowlist, Doc{Rg: "tor1", Seq: 1, Since: 1, Del: []string{"mkey:00"}}),
		"not json":     []byte("nope"),
	}
	for name, raw := range cases {
		if _, err := ks.Verify(raw); err == nil {
			t.Errorf("%s: accepted", name)
		}
	}
	// Tampered body (flip a byte after signing).
	var e Envelope
	_ = json.Unmarshal(good, &e)
	body, _ := b64.DecodeString(e.Body)
	body[len(body)-2] ^= 1
	e.Body = b64.EncodeToString(body)
	tb, _ := json.Marshal(e)
	if _, err := ks.Verify(tb); err == nil {
		t.Error("tampered body accepted")
	}
	// Padded base64 is rejected (strict b64url, no padding).
	_ = json.Unmarshal(good, &e)
	e.Sig = base64.URLEncoding.EncodeToString(mustB64(e.Sig))
	pb, _ := json.Marshal(e)
	if _, err := ks.Verify(pb); err == nil {
		t.Error("padded sig accepted")
	}
}

func mustB64(s string) []byte { b, _ := b64.DecodeString(s); return b }

